#!/usr/bin/env node
// Regenerate the entire Fumadocs corpus from immutable Mintlify source files.

import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import fs from 'node:fs/promises';
import {
  CONTENT_COLLECTIONS,
  CONTENT_DOCS_DIR,
  PRODUCTS,
  REPO_ROOT,
  UNMAPPED_ICON_REPORT,
  ensureDir,
} from './lib/shared.mjs';

const execFileAsync = promisify(execFile);
async function run(script, args) {
  const { stdout, stderr } = await execFileAsync(process.execPath, [script, ...args], { cwd: REPO_ROOT });
  if (stdout) process.stdout.write(stdout);
  if (stderr) process.stderr.write(stderr);
}

function parseArgs(argv) {
  const args = { dest: null };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--dest') args.dest = path.resolve(argv[++index]);
  }
  return args;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const replacingContent = args.dest === null;
  const destination = args.dest ?? path.join(REPO_ROOT, '_migration', '.content-docs-next');
  await fs.rm(destination, { recursive: true, force: true });
  await fs.mkdir(destination, { recursive: true });
  await ensureDir(path.dirname(UNMAPPED_ICON_REPORT));
  await fs.writeFile(UNMAPPED_ICON_REPORT, '# Generated by _migration/tools/run-migration.mjs. Unknown Card icons are appended below.\n', 'utf8');

  const converter = path.join(REPO_ROOT, '_migration', 'tools', 'mintlify-to-fumadocs.mjs');
  for (const collection of CONTENT_COLLECTIONS) {
    await run(converter, ['--collection', collection, '--src', REPO_ROOT, '--dest', destination]);
  }
  // Fail closed on unknown Card icons: the report is truncated above, so any
  // non-header line belongs to this run and must be mapped, not deferred.
  const iconReport = await fs.readFile(UNMAPPED_ICON_REPORT, 'utf8');
  const unmappedIcons = iconReport.split('\n').filter((line) => line && !line.startsWith('#'));
  if (unmappedIcons.length > 0) {
    throw new Error(`unmapped Card icons fail generation: ${unmappedIcons.join(', ')}`);
  }
  const metaBuilder = path.join(REPO_ROOT, '_migration', 'tools', 'docsjson-to-meta.mjs');
  for (const product of PRODUCTS) {
    await run(metaBuilder, ['--product', product, '--src', REPO_ROOT, '--dest', destination]);
  }

  const docsJson = JSON.parse(await fs.readFile(path.join(REPO_ROOT, 'docs.json'), 'utf8'));
  const rootMeta = {
    title: docsJson.name,
    // The TileTactician folder is the site root; '/' rewrites to it.
    pages: [...docsJson.navigation.products.map((entry) => entry.product.toLowerCase())],
  };
  await fs.writeFile(path.join(destination, 'meta.json'), `${JSON.stringify(rootMeta, null, 2)}\n`, 'utf8');

  // `content/docs` is generated output only. Building in a sibling first
  // avoids leaving a half-written corpus if conversion fails.
  if (replacingContent) {
    await fs.rm(CONTENT_DOCS_DIR, { recursive: true, force: true });
    await fs.mkdir(path.dirname(CONTENT_DOCS_DIR), { recursive: true });
    await fs.rename(destination, CONTENT_DOCS_DIR);
  }
  console.log(JSON.stringify({ destination }));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
